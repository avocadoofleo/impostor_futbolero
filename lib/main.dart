import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_auth/firebase_auth.dart';

import 'firebase_options.dart'; // This file is generated by the FlutterFire CLI
import 'package:impostor_futbolero/ui/router.dart';

void main() async {
  // Ensure Flutter is initialized.
  WidgetsFlutterBinding.ensureInitialized();

  // Initialize Firebase.
  await Firebase.initializeApp(
    options: DefaultFirebaseOptions.currentPlatform,
  );

  // Sign in anonymously to get a user ID.
  try {
    await FirebaseAuth.instance.signInAnonymously();
    print("Signed in with temporary account.");
  } catch (e) {
    print("Failed to sign in anonymously: $e");
  }

  // Run the app within Riverpod's scope.
  runApp(const ProviderScope(child: MyApp()));
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp.router(
      title: 'El Impostor Futbolero',
      routerConfig: router,
      theme: ThemeData(
        brightness: Brightness.dark,
        primaryColor: const Color(0xFF00BFFF),
        scaffoldBackgroundColor: const Color(0xFF0A0A0A),
        colorScheme: ColorScheme.fromSeed(
          seedColor: const Color(0xFF00BFFF),
          brightness: Brightness.dark,
        ),
        fontFamily: 'Roboto',
      ),
      debugShowCheckedModeBanner: false,
    );
  }
}
